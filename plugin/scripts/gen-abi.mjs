// Regenerates src/lib/payerAbi.ts from a Foundry build, so that the plugin ABI is the contract's ABI, never a
// hand copy. Run after `forge build` in ../contracts:  node scripts/gen-abi.mjs [path/to/contracts/out]
// (default ../contracts/out; pass another build, e.g. of a branch checked out elsewhere, as the argument).
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { resolve } from "node:path";
const out = process.argv[2] ? pathToFileURL(resolve(process.argv[2]) + "/") : new URL("../../contracts/out/", import.meta.url);
const load = (p) => JSON.parse(readFileSync(new URL(p, out), "utf8")).abi;
const payer = load("TrustGatedPayer.sol/TrustGatedPayer.json");
const ancre = load("AnchoredReputation.sol/AnchoredReputation.json").filter((x) =>
  ["assess", "passesAnchorPolicy", "policyOf", "identity", "reputation"].includes(x.name));
if (!ancre.some((x) => x.name === "passesAnchorPolicy")) throw new Error("this build has no passesAnchorPolicy (pre-02bis ABI?)");
const src = `// GENERATED by scripts/gen-abi.mjs from contracts/out — do not edit by hand.
export const payerAbi = ${JSON.stringify(payer, null, 2)} as const;

export const ancreAbi = ${JSON.stringify(ancre, null, 2)} as const;
`;
writeFileSync(new URL("../src/lib/payerAbi.ts", import.meta.url), src);
console.log(`payerAbi: ${payer.length} entries, ancreAbi: ${ancre.length} entries`);
