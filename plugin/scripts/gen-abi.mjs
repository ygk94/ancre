// Regenerates src/lib/payerAbi.ts from the Foundry build (contracts/out), so that the plugin ABI is the
// contract's ABI, never a hand copy. Run after `forge build` in ../contracts: node scripts/gen-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";
const out = new URL("../../contracts/out/", import.meta.url);
const load = (p) => JSON.parse(readFileSync(new URL(p, out), "utf8")).abi;
const payer = load("TrustGatedPayer.sol/TrustGatedPayer.json");
const ancre = load("AnchoredReputation.sol/AnchoredReputation.json").filter((x) =>
  ["assess", "isTrusted", "policyOf", "identity", "reputation"].includes(x.name));
const src = `// GENERATED by scripts/gen-abi.mjs from contracts/out — do not edit by hand.
export const payerAbi = ${JSON.stringify(payer, null, 2)} as const;

export const ancreAbi = ${JSON.stringify(ancre, null, 2)} as const;
`;
writeFileSync(new URL("../src/lib/payerAbi.ts", import.meta.url), src);
console.log(`payerAbi: ${payer.length} entries, ancreAbi: ${ancre.length} entries`);
